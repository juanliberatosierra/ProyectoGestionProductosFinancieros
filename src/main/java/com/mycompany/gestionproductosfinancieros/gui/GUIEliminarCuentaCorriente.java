    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
            try {
            int numeroCuenta = Integer.parseInt(txtNumeroCuenta.getText().trim());

            Map<Integer, ProductoFinanciero> productos
                    = ServicioProductoFinanciero.getProductos();

            ProductoFinanciero pf = productos.get(numeroCuenta);

            if (pf instanceof CuentaCorriente) {

                int respuesta = JOptionPane.showConfirmDialog(
                        this,
                        "¿Está seguro de eliminar esta cuenta?",
                        "Confirmar eliminación",
                        JOptionPane.YES_NO_OPTION
                );

                if (respuesta == JOptionPane.YES_OPTION) {

                    ServicioProductoFinanciero.eliminarProducto(numeroCuenta);

                    JOptionPane.showMessageDialog(
                            this,
                            "Cuenta de ahorro eliminada correctamente."
                    );

                    txtNumeroCuenta.setText("");
                    txtTitular.setText("");
                    txtFechaApertura.setText("");
                    txtSaldo.setText("");
                    txtCuotaManejo.setText("");
                    txtTipoCuenta.setText("");
                }

            } else if (pf == null) {

                JOptionPane.showMessageDialog(
                        this,
                        "No se encontró una cuenta con ese número."
                );

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "El número de cuenta corresponde a otro tipo de producto."
                );
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un número de cuenta válido."
            );
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

