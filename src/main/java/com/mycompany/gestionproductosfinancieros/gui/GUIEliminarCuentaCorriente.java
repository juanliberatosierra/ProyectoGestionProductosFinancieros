    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            int numeroCuenta = Integer.parseInt(txtNumeroCuenta.getText().trim());

            Map<Integer, ProductoFinanciero> productos =
            ServicioProductoFinanciero.getProductos();

            ProductoFinanciero pf = productos.get(numeroCuenta);

            if (pf instanceof CuentaCorriente) {

                CuentaCorriente cuenta = (CuentaCorriente) pf;

                txtTitular.setText(cuenta.getTitular());
                txtFechaApertura.setText(cuenta.getFechaApertura().toString());
                txtSaldo.setText(String.valueOf(cuenta.getSaldo()));
                txtCuotaManejo.setText(String.valueOf(cuenta.getCuotaManejo()));
                txtTipoCuenta.setText(String.valueOf(cuenta.getTipoCuenta()));

            } else if (pf == null) {

                JOptionPane.showMessageDialog(
                    this,
                    "No se encontró una cuenta con ese número."
                );

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "El número de cuenta corresponde a otro tipo de producto."
                );
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "Ingrese un número de cuenta válido."
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
            );
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

