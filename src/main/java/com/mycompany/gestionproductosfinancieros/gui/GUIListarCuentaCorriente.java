    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        Map<Integer, ProductoFinanciero> productos;
        productos = ServicioProductoFinanciero.getProductos();

        DefaultTableModel modelo = (DefaultTableModel) tblProductoFinanciero.getModel();
        modelo.setRowCount(0);

        for (Map.Entry<Integer, ProductoFinanciero> producto : productos.entrySet()) {

            Integer numeroCuenta = producto.getKey();

            ProductoFinanciero pf = producto.getValue();

            if (pf instanceof CuentaCorriente) {

                CuentaCorriente cuenta = (CuentaCorriente) pf;

                Object[] fila = new Object[]{
                    numeroCuenta,
                    cuenta.getTitular(),
                    cuenta.getFechaApertura(),
                    cuenta.getSaldo(),
                    cuenta.getCuotaManejo(),
                    cuenta.getTipoCuenta(),
                    cuenta.calcularSaldoFinal()
                };

                modelo.addRow(fila);
            }
        }
    }//GEN-LAST:event_btnListarActionPerformed

